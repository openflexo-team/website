#!/usr/bin/env python3
"""Regenerate docs/guide/fml-specification/ from the Markdown sources of the FML specification.

Source of truth: the `spec/` directory of the openflexo-core repository (one Markdown file per
chapter, written for GitHub and for reading in an editor). This script copies each file into the
documentation of the site with what Docusaurus needs: a front matter, file names without number
prefix, links rewritten, code fences without language tag, notes turned into admonitions, and the
characters MDX would read as markup escaped outside code. Python standard library only: this
repository's package-lock.json cannot be regenerated, so nothing here may add an npm dependency, and
only the generated pages are committed.

Run from the website repo root:

    python3 scripts/generate_fml_specification.py

Requires a clone of openflexo-core next to this repository -- pass --spec-dir to point elsewhere.
Re-run it whenever the specification changes. A new chapter is added to CHAPTERS below.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = ROOT / "docs" / "guide" / "fml-specification"
DEFAULT_SPEC_DIR = ROOT.parent / "openflexo-core" / "spec"
SOURCE_URL = "https://github.com/openflexo-team/openflexo-core/blob/3.0/"

# (source file, output file, sidebar position, sidebar label, description)
CHAPTERS = [
    ("README.md", "index.md", 0, "Overview",
     "The specification of FML, the Flexo Modeling Language, release 3.0: how it is organised and how to read it."),
    ("01-introduction.md", "introduction.md", 1, "1. Introduction",
     "What FML is, its two textual surfaces, the notation of the specification and what conformance means."),
    ("02-lexical-structure.md", "lexical-structure.md", 2, "2. Lexical structure",
     "Characters, comments, the lexical states, identifiers, keywords, literals, operators and separators."),
    ("03-compilation-units.md", "compilation-units.md", 3, "3. Compilation units",
     "The layout of a .fml file: namespaces, use and import declarations, type definitions, resources and addresses."),
    ("04-types.md", "types.md", 4, "4. Types",
     "Primitive, reference, generic and technology-specific types; versions, cardinalities and the typing space."),
    ("05-models-and-concepts.md", "models-and-concepts.md", 5, "5. Models, concepts, events and enums",
     "The declarations that structure a program: containment, inheritance, enums, events and invariants."),
    ("06-properties.md", "properties.md", 6, "6. Properties",
     "Typed, multi-valued, expression, role-bound, abstract and get/set properties."),
    ("07-behaviours.md", "behaviours.md", 7, "7. Behaviours",
     "Methods, creation and deletion schemes, event listeners and technology-specific behaviours."),
    ("08-statements.md", "statements.md", 8, "8. Statements",
     "Blocks, local variables, assignments, conditions, loops and returns."),
    ("09-expressions.md", "expressions.md", 9, "9. Expressions",
     "Operators and precedence, numbers and strings, paths and name resolution, new, null."),
    ("10-edition-actions.md", "edition-actions.md", 10, "10. Edition actions",
     "select, delete, log, fire, notify, connect, matching and technology actions."),
    ("11-annotations.md", "annotations.md", 11, "11. Annotations",
     "The syntax of annotations and the ones the platform interprets."),
    ("12-fml-script.md", "fml-script.md", 12, "12. FML-script",
     "The command and script surface: directives, resources, loading, instantiation and assertions."),
    ("13-execution-model.md", "execution-model.md", 13, "13. Execution model",
     "Instances, containment, how a behaviour runs, failure, change notification and validation."),
    ("appendix-a-grammar.md", "appendix-a-grammar.md", 14, "A. Grammar summary",
     "The complete syntax of FML in EBNF."),
    ("appendix-b-known-deviations.md", "appendix-b-known-deviations.md", 15, "B. Known deviations",
     "Where the implementation departs from the language, and what to write instead."),
    ("appendix-c-example.md", "appendix-c-example.md", 16, "C. A complete example",
     "One model and the script that runs it, with the place of each construct in the specification."),
]

CATEGORY = '''{
  "label": "FML specification",
  "position": 3.5,
  "link": {
    "type": "doc",
    "id": "guide/fml-specification/index"
  }
}
'''

HEADER = """<!-- Generated by scripts/generate_fml_specification.py from the spec/ directory of
     openflexo-core ({source}). Do not hand-edit -- re-run the script instead. -->"""


def page_name(source_name):
    for source, output, *_ in CHAPTERS:
        if source == source_name:
            return output
    return None


def rewrite_link(match):
    text, target = match.group(1), match.group(2)
    if target.startswith(("http://", "https://", "#", "mailto:")):
        return match.group(0)
    path, _, anchor = target.partition("#")
    if path.startswith("../"):
        return f"[{text}]({SOURCE_URL}{path[3:]}{'#' + anchor if anchor else ''})"
    output = page_name(path)
    if output is None:
        raise SystemExit(f"link to an unknown file: {target}")
    return f"[{text}]({output}{'#' + anchor if anchor else ''})"


def escape_mdx(line):
    """Escape what MDX reads as markup in a line of prose; inline code is left alone."""
    parts = re.split(r"(`[^`]*`)", line)
    for i in range(0, len(parts), 2):
        parts[i] = (parts[i].replace("{", "\\{").replace("}", "\\}")
                    .replace("<", "&lt;"))
    return "".join(parts)


def convert_notes(lines):
    """Turn the blockquotes that open with '**Implementation note.**' into admonitions."""
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("> **Implementation note.**"):
            body = [line[len("> **Implementation note.**"):].strip()]
            i += 1
            while i < len(lines) and lines[i].startswith(">"):
                body.append(lines[i][1:].strip())
                i += 1
            out.append(":::note[Implementation note]")
            out.extend(b for b in body if b != "" or True)
            out.append(":::")
            continue
        out.append(line)
        i += 1
    return out


def convert(text, source, position, label, description):
    lines = text.rstrip("\n").split("\n")
    title = re.sub(r"^#\s+", "", lines[0])
    if not lines[0].startswith("# "):
        raise SystemExit(f"{source}: the first line must be the title")
    lines = convert_notes(lines)
    out, in_fence = [], False
    for line in lines:
        if line.startswith("```"):
            in_fence = not in_fence
            out.append("```" if in_fence else "```")
            continue
        if in_fence:
            out.append(line)
            continue
        line = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", rewrite_link, line)
        if line.startswith(":::"):
            out.append(line)
        else:
            out.append(escape_mdx(line))
    front = "\n".join([
        "---",
        f"sidebar_position: {position}",
        f"sidebar_label: \"{label}\"",
        f"title: \"{title}\"",
        f"description: \"{description}\"",
        "---",
    ])
    header = HEADER.format(source=f"spec/{source}")
    return front + "\n\n" + header + "\n\n" + "\n".join(out) + "\n"


def build_pages(spec_dir):
    pages = {}
    for source, output, position, label, description in CHAPTERS:
        path = spec_dir / source
        if not path.is_file():
            raise SystemExit(f"{path} is missing: is openflexo-core next to this repository?")
        pages[output] = convert(path.read_text(), source, position, label, description)
    pages["_category_.json"] = CATEGORY
    known = {source for source, *_ in CHAPTERS}
    extra = sorted(p.name for p in spec_dir.glob("*.md") if p.name not in known)
    if extra:
        raise SystemExit(f"specification files that are not in CHAPTERS: {', '.join(extra)}")
    return pages


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--spec-dir", type=Path, default=DEFAULT_SPEC_DIR,
                        help="the spec/ directory of openflexo-core")
    args = parser.parse_args()
    pages = build_pages(args.spec_dir)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, content in pages.items():
        (OUTPUT_DIR / name).write_text(content)
    stale = sorted(p.name for p in OUTPUT_DIR.iterdir() if p.name not in pages)
    for name in stale:
        (OUTPUT_DIR / name).unlink()
    print(f"wrote {len(pages)} files in {OUTPUT_DIR.relative_to(ROOT)}" + (f", removed {stale}" if stale else ""))


if __name__ == "__main__":
    sys.exit(main())
